// Extracts the Kompetenzerwartungen from captured LehrplanPLUS Grundschule
// pages (Bayern) into a reference framework file in official-de/frameworks/.
//   node official-de/tools/by-lehrplanplus.mjs mathe   (from the rnd root)
// One page per two-year plan (1/2, 3/4). The output is generated: rerun this
// script, never edit the YAML.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const DOCS = {
  mathe: {
    id: "by-mathe-2014",
    title: "LehrplanPLUS Grundschule Bayern, Fachlehrplan Mathematik",
    domain: "math",
    prefix: "M",
    pages: [
      ["1/2", "end-klasse-2", "official-de/by/raw/lehrplanplus-gs-mathematik-jgs1.html", "https://www.lehrplanplus.bayern.de/fachlehrplan/grundschule/1/mathematik"],
      // Jahrgangsstufen 3 and 4 share one two-year plan (M3/4); the jgs4 page repeats it.
      ["3/4", "end-klasse-4", "official-de/by/raw/lehrplanplus-gs-mathematik-jgs3.html", "https://www.lehrplanplus.bayern.de/fachlehrplan/grundschule/3/mathematik"],
    ],
  },
};
const doc = DOCS[process.argv[2]];
if (!doc) { console.error(`usage: by-lehrplanplus.mjs <${Object.keys(DOCS).join("|")}>`); process.exit(1); }

const decode = (s) => s.replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#0?39;/g, "'")
  .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n))).replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)));
const textLines = (html) => decode(html.replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>/g, "").replace(/<(li|p|h\d|div|br|tr|td)[^>]*>/g, "\n").replace(/<[^>]+>/g, ""))
  .split("\n").map((l) => l.replace(/\s+/g, " ").trim()).filter(Boolean);
const META = /^(Prozessbezogene Kompetenzen:|Gegenstandsbereiche:|Übergreifende Ziele:|Querverweise:|DaZ:|Servicematerialien|Inklusion|Digital|Abschnitt hinzufügen|\(Referenz aus|Förderschule|Grundschule |\|)/;
const PROCESS = /^(kommunizieren|argumentieren|modellieren|Probleme lösen|Darstellungen verwenden)( \| .*)?$/;

const objectives = [];
for (const [jgs, band, file] of doc.pages) {
  const L = textLines(readFileSync(join(ROOT, file), "utf8"));
  const secRe = new RegExp(`^${doc.prefix}${jgs.replace("/", "\\/")} (\\d)\\.(\\d) (.+)$`);
  const areaRe = new RegExp(`^${doc.prefix}${jgs.replace("/", "\\/")} Lernbereich (\\d): (.+)$`);
  let area = null, sec = null, inList = false, n = 0;
  for (let i = 0; i < L.length; i++) {
    const l = L[i];
    let m;
    if ((m = l.match(areaRe))) { area = m[2]; inList = false; continue; }
    if ((m = l.match(secRe))) { sec = { code: `${m[1]}.${m[2]}`, title: m[3] }; inList = false; n = 0; continue; }
    if (l === "Die Schülerinnen und Schüler ...") { inList = !!sec; continue; }
    if (!inList) continue;
    if (/^Inhalte zu den Kompetenzen/.test(l) || /^Kompetenzerwartungen und Inhalte/.test(l)) { inList = l.startsWith("Kompetenzerwartungen"); continue; }
    if (META.test(l) || PROCESS.test(l) || l === area) continue;
    // A statement can be split over lines; join until it ends in punctuation.
    let stmt = l;
    while (/^[a-zäöü]/.test(stmt) && !/[.:;)]$/.test(stmt) && L[i + 1] && !META.test(L[i + 1]) && !PROCESS.test(L[i + 1])) stmt += " " + L[++i];
    if (/^[a-zäöü]/.test(stmt) && /[.:;)]$/.test(stmt)) {
      n++;
      const procs = PROCESS.test(L[i + 2] ?? "") ? L[i + 2] : (PROCESS.test(L[i + 1] ?? "") ? L[i + 1] : null);
      objectives.push({ code: `${doc.id}.j${jgs.replace("/", "")}.${sec.code}.${n}`, kind: "content", area, group: `${sec.code} ${sec.title}`, band, jgs, text: stmt.replace(/\.$/, ""), process: procs });
    }
  }
}

const q = (s) => JSON.stringify(s);
let out = `# Generated by official-de/tools/by-lehrplanplus.mjs from the captured LehrplanPLUS pages.
# Do not edit. Objective texts are verbatim; codes are ours (j12, j34 = Jahrgangsstufen).
# Bayern plans in two-year blocks: end-klasse-2 covers 1/2, end-klasse-4 covers 3/4.
framework: ${doc.id}
title: ${q(doc.title)}
url: ${q(doc.pages[0][3])}
country: DE
land: BY
domain: ${doc.domain}
standards:
`;
for (const o of objectives) {
  out += `  - code: ${o.code}\n    kind: ${o.kind}\n    area: ${q(o.area)}\n    group: ${q(o.group)}\n    band: ${o.band}\n`;
  if (o.process) out += `    process: ${q(o.process)}\n`;
  out += `    text: ${q(o.text)}\n`;
}
writeFileSync(join(ROOT, `official-de/frameworks/${doc.id}.yaml`), out);
const by = {}; for (const o of objectives) by[`${o.jgs} ${o.area}`] = (by[`${o.jgs} ${o.area}`] ?? 0) + 1;
console.log(`official-de/frameworks/${doc.id}.yaml: ${objectives.length} objectives`); console.table(by);
