// Builds a Twist framework file from verbatim sentences of a KMK report that
// has no bullet-list standards (Fremdsprachen in der Grundschule, 2013).
//   node official-de/tools/kmk-quotes.mjs fremdsprachen   (from the rnd root)
// Each objective is a quote; the script fails if a quote is not found in the
// captured text, so the YAML can never drift from the document.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const SKILLS = "Die funktional-kommunikativen Kompetenzen umfassen die Fertigkeiten des Hör-/Hör-Sehverstehens und des Sprechens sowie des Leseverstehens und Schreibens und der Sprachmittlung.";
const DOCS = {
  fremdsprachen: {
    id: "kmk-fremdsprachen-gs-2013",
    text: "official-de/kmk/text/2013_10_17-Fremdsprachen-in-der-Grundschule.txt",
    title: "Fremdsprachen in der Grundschule – Sachstand und Konzeptionen 2013 (Bericht der KMK vom 17.10.2013)",
    url: "https://www.kmk.org/fileadmin/Dateien/veroeffentlichungen_beschluesse/2013/2013_10_17-Fremdsprachen-in-der-Grundschule.pdf",
    domain: "fl",
    band: "end-klasse-4",
    level: "Das angestrebte Niveau der funktionalen kommunikativen Kompetenzen am Ende der Klassenstufe 4 ist am Referenzniveau A1 des Gemeinsamen europäischen Referenzrahmens ausgerichtet.",
    objectives: [
      ["hoeren", "Hör-/Hör-Sehverstehen", SKILLS],
      ["sprechen", "Sprechen", SKILLS],
      ["lesen", "Leseverstehen", SKILLS],
      ["schreiben", "Schreiben", SKILLS],
      ["sprachmittlung", "Sprachmittlung", SKILLS],
      ["sprachliche-mittel", "Sprachliche Mittel", "Dabei zielt der Fremdsprachenunterricht auf den Erwerb grundlegender kommunikativer Fähigkeiten und Fertigkeiten, die kontinuierlich entwickelt werden, sowie elementarer sprachlicher Mittel, die die Schülerinnen und Schüler in lebensnahen und kindgerechten Situationen erproben und festigen können."],
      ["interkulturell", "Interkulturelle Kompetenzen", "Entsprechend heißt es in den Lehrplänen der Länder, dass im Fremdsprachenunterricht das Wissen um andere Kulturen erweitert wird, indem Kenntnisse der Unterschiede und Gemeinsamkeiten anderer Kulturen erworben werden."],
      ["sprachlernkompetenz", "Sprachlernkompetenz", "Hierzu gehört, Vertrauen in die eigenen sprachlichen Fähigkeiten zu gewinnen, Lern- und Arbeitstechniken anzuwenden, eigene Lernstrategien zu entwickeln und Hilfsmittel zunehmend selbständig zu nutzen."],
      ["sprachbewusstheit", "Sprachbewusstheit", "Durch Vergleiche mit der deutschen Sprache und ggf. anderen Herkunftssprachen wird angestrebt, Sprachbewusstheit und Sprachlernkompetenz zu entwickeln."],
    ],
  },
};
const doc = DOCS[process.argv[2]];
if (!doc) { console.error(`usage: kmk-quotes.mjs <${Object.keys(DOCS).join("|")}>`); process.exit(1); }

const raw = readFileSync(join(ROOT, doc.text), "utf8");
// Join the text as one run, dropping hyphenation at line ends, and note where pages end.
const lines = raw.split("\n");
let flat = "", pages = [];
for (const l of lines) {
  const t = l.trim();
  // Page numbers stand alone and increase; a lone smaller digit is a footnote mark.
  if (/^\d{1,3}$/.test(t)) { if (Number(t) > (pages.at(-1)?.[1] ?? 0)) pages.push([flat.length, Number(t)]); continue; }
  if (/(\p{L})-$/u.test(flat) && /^\p{Ll}/u.test(t)) flat = flat.slice(0, -1) + t; // hyphenated word
  else if (/-$/.test(flat) && /^\//.test(t)) flat += t; // "Hör-" + "/Hör-Sehverstehens"
  else flat += (flat && t ? " " : "") + t;
}
flat = flat.replace(/\s+/g, " ");
const pageAt = (i) => (pages.find(([at]) => at >= i) ?? [0, null])[1];
const find = (q) => { const i = flat.indexOf(q); if (i < 0) { console.error(`quote not found: "${q.slice(0, 80)}…"`); process.exit(1); } return pageAt(i); };

const q = (s) => JSON.stringify(s);
let out = `# Generated by official-de/tools/kmk-quotes.mjs from the captured KMK report.
# Do not edit. Texts are verbatim sentences; areas and codes are ours. The report
# describes the Länder's shared aims; level target: ${doc.level}
framework: ${doc.id}
title: ${q(doc.title)}
url: ${q(doc.url)}
country: DE
domain: ${doc.domain}
band: ${doc.band}
level: A1
standards:
`;
find(doc.level);
for (const [code, area, text] of doc.objectives) out += `  - code: ${doc.id}.${code}\n    kind: content\n    area: ${q(area)}\n    page: ${find(text)}\n    text: ${q(text)}\n`;
writeFileSync(join(ROOT, `twist/frameworks/de/${doc.id}.yaml`), out);
console.log(`twist/frameworks/de/${doc.id}.yaml: ${doc.objectives.length} objectives, all quotes found`);
