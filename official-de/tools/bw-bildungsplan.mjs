// Extracts the Teilkompetenzen from captured Bildungsplan 2016 Grundschule
// section pages (Baden-Württemberg) into a reference framework file in official-de/frameworks/.
//   node official-de/tools/bw-bildungsplan.mjs mathe   (from the rnd root)
// One HTML page per section of the inhaltsbezogene Kompetenzen (official-de/bw/raw/ik/).
// The full plan is also captured as a PDF (bw/raw/bp2016bw-gs-mathematik.pdf).
// The output is generated: rerun this script, never edit the YAML.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const DOCS = {
  mathe: {
    id: "bw-mathe-2016",
    title: "Bildungsplan 2016 Grundschule Baden-Württemberg, Mathematik",
    url: "https://www.bildungsplaene-bw.de/,Lde/LS/BP2016BW/ALLG/GS/M",
    domain: "math",
    dir: "official-de/bw/raw/ik",
    match: /^GS_M_IK_(\d-\d)_(\d\d)_(\d\d)\.html$/,
    areas: { "01": "Zahlen und Operationen", "02": "Raum und Form", "03": "Größen und Messen", "04": "Daten, Häufigkeit und Wahrscheinlichkeit" },
  },
};
const doc = DOCS[process.argv[2]];
if (!doc) { console.error(`usage: bw-bildungsplan.mjs <${Object.keys(DOCS).join("|")}>`); process.exit(1); }

const clean = (s) => s.replace(/<[^>]+>/g, " ").replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&quot;/g, '"').replace(/&shy;|­/g, "")
  .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n))).replace(/\s+/g, " ").trim();

const objectives = [];
for (const f of readdirSync(join(ROOT, doc.dir)).sort()) {
  const m = f.match(doc.match);
  if (!m) continue;
  const [, band, area, sec] = m;
  const html = readFileSync(join(ROOT, doc.dir, f), "utf8");
  const title = clean(html.match(/<title>([^<]*)/)[1]).replace(/ - Bildungsplan.*$/, "");
  const re = /class="teilkompetenzNumber">\((\d+)\)<\/div>\s*<div class="teilkompetenzText">([\s\S]*?)<\/div>/g;
  let t;
  while ((t = re.exec(html))) {
    objectives.push({
      code: `${doc.id}.k${band.replace("-", "")}.${Number(area)}.${Number(sec)}.${t[1]}`,
      area: doc.areas[area], group: title, band: band === "1-2" ? "end-klasse-2" : "end-klasse-4", text: clean(t[2]),
    });
  }
}

const q = (s) => JSON.stringify(s);
let out = `# Generated by official-de/tools/bw-bildungsplan.mjs from the captured Bildungsplan pages.
# Do not edit. Objective texts are verbatim; codes are ours (k12, k34 = Klassen 1/2, 3/4).
# Baden-Württemberg plans in two-year blocks: end-klasse-2 covers 1/2, end-klasse-4 covers 3/4.
framework: ${doc.id}
title: ${q(doc.title)}
url: ${q(doc.url)}
country: DE
land: BW
domain: ${doc.domain}
objectives:
`;
for (const o of objectives) out += `  - code: ${o.code}\n    kind: content\n    area: ${q(o.area)}\n    group: ${q(o.group)}\n    band: ${o.band}\n    text: ${q(o.text)}\n`;
writeFileSync(join(ROOT, `official-de/frameworks/${doc.id}.yaml`), out);
const by = {}; for (const o of objectives) by[`${o.band} ${o.area}`] = (by[`${o.band} ${o.area}`] ?? 0) + 1;
console.log(`official-de/frameworks/${doc.id}.yaml: ${objectives.length} objectives`); console.table(by);
