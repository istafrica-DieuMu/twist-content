// Splits the remaining (not yet captured) exercise files into chunk lists for step 1f:
// German-DE first, then English-GB, one chunk per subject, outdated courses last.
// A course listed in both curricula goes to German-DE. Writes tools/lists/1f/NN-<curriculum>-<subject>.txt.
import { DatabaseSync } from "node:sqlite";
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
const db = new DatabaseSync("catalogue/catalogue.db", { readOnly: true });
const etag = {};
for (const f of readdirSync("anton/api/plan").filter((f) => f.endsWith(".json"))) {
  const d = JSON.parse(readFileSync("anton/api/plan/" + f, "utf8"));
  for (const t of d.topics || []) for (const b of t.blocks || []) for (const l of b.levels || []) etag["level/" + l.path.replace(/^\/\.\.\//, "")] = l.etag;
}
const inCur = (cur) => new Set(db.prepare("SELECT course FROM course_curriculum WHERE curriculum = ?").all(cur).map((r) => r.course));
const de = inCur("de"), gb = inCur("en_gb");
const order = ["nateng", "natdeu", "mat", "deu", "sldeu", "eng", "sleng", "sci", "preschool", "mus", "geo", "his", "sel", "com", "bio", "chem", "phy", "lang"];
const rows = db.prepare(`SELECT e.file_id f, e.bytes b, e.course, c.subject s, c.subject_name sn, c.outdated o
  FROM exercise e JOIN course c ON c.id = e.course ORDER BY e.course, e.lesson, e.position`).all()
  .filter((r) => !existsSync("anton/api/" + r.f + ".json"));
const chunks = {};
for (const r of rows) {
  const cur = de.has(r.course) ? "de" : gb.has(r.course) ? "en_gb" : "other";
  const key = r.o ? `${cur}|zz-outdated` : `${cur}|${r.s}`;
  (chunks[key] ||= { cur, s: r.o ? "outdated" : r.s, sn: r.o ? "Outdated courses" : r.sn, rows: [] }).rows.push(r);
}
const rank = (c) => (c.cur === "de" ? 0 : c.cur === "en_gb" ? 1 : 2) * 100 + (c.s === "outdated" ? 99 : order.indexOf(c.s) === -1 ? 98 : order.indexOf(c.s));
const list = Object.values(chunks).sort((a, b) => rank(a) - rank(b));
const lines = ["| # | Chunk file | Curriculum | Subject | Files | MB | Hours at 1.35 s |", "|---|---|---|---|---|---|---|"];
list.forEach((c, i) => {
  const name = `${String(i + 1).padStart(2, "0")}-${c.cur}-${c.s}.txt`;
  writeFileSync("anton/tools/lists/1f/" + name, c.rows.map((r) => `${r.f} ${etag[r.f]}`).join("\n") + "\n");
  const mb = c.rows.reduce((s, r) => s + r.b, 0) / 1e6;
  lines.push(`| ${i + 1} | \`${name}\` | ${c.cur === "de" ? "German-DE" : "English-GB"} | ${c.sn} | ${c.rows.length} | ${mb.toFixed(1)} | ${(c.rows.length * 1.35 / 3600).toFixed(1)} |`);
});
writeFileSync("anton/tools/lists/1f/README.md", "# 1f chunks\n\nGenerated by `tools/chunk-1f.mjs` from files not yet captured. Run one chunk with\n`node tools/fetch.mjs levels tools/lists/1f/<file> --delay 1` from `anton/`.\nCreate `tools/STOP` to end a run after the file in flight.\n\n" + lines.join("\n") + "\n");
console.log(lines.join("\n"));
